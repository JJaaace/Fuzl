import assert from 'node:assert/strict';
import { test } from 'node:test';
import { randomBytes, randomUUID } from 'node:crypto';
import { answerText, answersFit, applyGuestAnswer, emptySummary, inviteInputSchema, responseInputSchema, sessionInputSchema } from '@fuzl/planning';
import type { OrganizerReply } from '@fuzl/planning';
import { redactAnswers, digest } from './store.js';
const q = randomUUID(), p = randomUUID();
const question = { id: q, text: 'What is your spending limit?', type: 'budget' as const, required: false };
const budget = { questionId: q, kind: 'budget' as const, state: 'known' as const, amount: 0, currency: null, visibility: 'private' as const };
test('guest contract distinguishes private zero, explicit unknown and blank without inventing currency', () => {
    assert.equal(responseInputSchema.parse({ alias: 'Sam', answers: [budget] }).answers[0].state, 'known');
    assert.equal(answerText(budget), '0 (currency unknown)');
    assert.equal(answerText({ ...budget, state: 'unknown', amount: null }), 'Explicitly unknown');
    assert.equal(answerText({ ...budget, state: 'blank', amount: null }), 'Left blank');
    for (const amount of [-1, 1.001, 1000001, Infinity])
        assert.equal(responseInputSchema.safeParse({ alias: 'Sam', answers: [{ ...budget, amount }] }).success, false);
    assert.equal(responseInputSchema.safeParse({ alias: 'Sam', answers: [{ ...budget, currency: '$' }] }).success, false);
    assert.equal(answersFit([{ ...question, required: true }], { alias: 'Sam', answers: [{ ...budget, state: 'blank', amount: null }] }), false);
    assert.equal(answersFit([{ ...question, required: true }], { alias: 'Sam', answers: [{ ...budget, state: 'unknown', amount: null }] }), true);
    assert.equal(inviteInputSchema.safeParse({ title: 'Approved', questions: [question], approved: false, replace: false, days: 7, sessionRevision: 1 }).success, false);
});
test('organizer redaction is an output allowlist even for a private amount accidentally stored in public JSON', () => {
    assert.deepEqual(redactAnswers([{ ...budget, amount: 9876.54 }]), [{ questionId: q, kind: 'budget', state: 'private' }]);
    assert.deepEqual(redactAnswers([{ ...budget, visibility: 'organizer' }]), [{ ...budget, visibility: 'organizer' }]);
    assert.throws(() => redactAnswers([{ ...budget, rawConversation: 'private data' }]));
    const secret = randomBytes(32).toString('base64url');
    assert.equal(secret.length, 43);
    assert.equal(digest(secret).length, 64);
    assert.ok(!digest(secret).includes(secret));
});
test('explicit match/apply preserves original sources and unrelated values and marks mapped tentative AI history', () => {
    const source = randomUUID(), speaker = randomUUID(), old = randomUUID();
    const summary = { ...emptySummary(), participants: [{ id: p, name: 'Sam' }], speakers: [{ id: speaker, label: 'Imported Sam', participantId: p }], sources: [{ id: source, speakerId: speaker, text: 'Maybe my limit is 20' }], facts: [{ id: old, kind: 'budget' as const, amount: 20, currency: 'USD', subject: { kind: 'speaker' as const, speakerId: speaker }, status: 'tentative' as const, strength: 'flexible' as const, sourceIds: [source], extraction: { reviewed: false, reportedStatus: 'tentative' as const, uncertainty: 'Maybe', scope: 'current' as const, supersedes: [] } }], questions: [{ id: 'missing', kind: 'missing' as const, text: 'Budget?', resolution: null, relatedFactIds: [old] }] };
    const reply: OrganizerReply = { id: randomUUID(), inviteId: randomUUID(), alias: 'Sam guest', revision: 1, updatedAt: new Date().toISOString(), questions: [question], answers: [{ ...budget, visibility: 'organizer' }] };
    const applied = applyGuestAnswer(summary, reply, q, p, 'missing', old);
    assert.equal(summary.facts[0].amount, 20);
    assert.deepEqual(applied.sources[0], summary.sources[0]);
    assert.ok(applied.facts[0].kind === 'budget' && applied.facts[0].amount === 0 && applied.facts[0].currency === null);
    assert.equal(applied.facts[1].extraction?.scope, 'historical');
    assert.equal(applied.facts[0].status, 'proposed');
    assert.ok(applied.questions[0].resolution?.includes('Guest reply'));
    assert.ok(sessionInputSchema.safeParse({ title: 'Synthetic', origin: 'ai', summaryVersion: 1, provenance: [], summary: applied }).success);
    assert.throws(() => applyGuestAnswer(applied, reply, q, p, null, null), /already applied/);
    assert.throws(() => applyGuestAnswer(applied, reply, q, p, 'missing', null, 'question'), /no longer unresolved/);
    const nextQuestion = randomUUID();
    const nextReply = { ...reply, questions: [...reply.questions, { ...question, id: nextQuestion }], answers: [...reply.answers, { ...budget, questionId: nextQuestion, visibility: 'organizer' as const }] };
    const second = applyGuestAnswer(applied, nextReply, nextQuestion, p, null, null);
    assert.equal(second.speakers.length, applied.speakers.length);
    assert.equal(second.sources.length, applied.sources.length + 1);
    assert.equal(second.questions[0].resolution, applied.questions[0].resolution);
    const resolved = applyGuestAnswer(summary, reply, q, p, 'missing', null, 'question');
    assert.equal(resolved.facts.length, 1);
    assert.equal(resolved.sources.length, 1);
    assert.equal(resolved.questions[0].guest?.responseId, reply.id);
    assert.throws(() => applyGuestAnswer(summary, { ...reply, answers: [{ questionId: q, kind: 'budget', state: 'private' }] }, q, p, null, null));
    assert.throws(() => applyGuestAnswer(summary, reply, q, 'wrong', null, null));
    const unknown = applyGuestAnswer(summary, { ...reply, questions: [{ ...question, type: 'availability' }], answers: [{ questionId: q, kind: 'availability', state: 'unknown', text: null }] }, q, p, null, null);
    assert.ok(unknown.facts[0].kind === 'schedule' && unknown.facts[0].description === null && unknown.facts[0].exactDate === null);
    assert.ok(unknown.facts[0].guest?.sourceText.includes('Explicitly unknown'));
});
test('public routes reject foreign origins, malformed/oversized input and sanitize unexpected storage failures', async (t) => {
    const { createApp } = await import('../app.js');
    const calls: string[] = [];
    const token = randomBytes(32).toString('base64url');
    const store = { form: async () => { calls.push('form'); return { title: 'Approved', questions: [question], expiresAt: '2030-01-01T00:00:00.000Z' }; }, submit: async () => { throw new Error('synthetic-private-secret-and-answer'); } } as unknown as import('./store.js').GuestStore;
    let logs = 0;
    t.mock.method(console, 'error', () => { logs++; });
    const server = createApp({ guests: { store: () => store } }).listen(0, '127.0.0.1');
    await new Promise<void>(r => server.once('listening', r));
    t.after(() => new Promise<void>(r => server.close(() => r())));
    const address = server.address() as import('node:net').AddressInfo;
    const base = `http://127.0.0.1:${address.port}/api/guest`;
    const headers = { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' };
    assert.equal((await fetch(base + '/form', { headers: { ...headers, Origin: 'https://unrelated.example' } })).status, 403);
    assert.equal(calls.length, 0);
    const form = await fetch(base + '/form', { headers });
    assert.equal(form.status, 200);
    assert.equal(form.headers.get('referrer-policy'), 'no-referrer');
    assert.ok(form.headers.get('cache-control')?.includes('no-store'));
    assert.equal(form.headers.get('access-control-allow-origin'), null);
    assert.deepEqual(calls, ['form']);
    assert.equal((await fetch(base + '/responses', { method: 'POST', headers, body: '{broken' })).status, 400);
    assert.equal((await fetch(base + '/responses', { method: 'POST', headers, body: JSON.stringify({ data: 'x'.repeat(17000) }) })).status, 413);
    const result = await fetch(base + '/responses', { method: 'POST', headers, body: JSON.stringify({ submissionId: randomUUID(), editToken: randomBytes(32).toString('base64url'), payload: { alias: 'Sam', answers: [budget] } }) });
    assert.equal(result.status, 503);
    assert.ok(!(await result.text()).includes('synthetic-private-secret'));
    assert.equal(logs, 0);
});
